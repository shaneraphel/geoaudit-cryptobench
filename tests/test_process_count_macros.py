"""A process count must be generated from the ledger, and must mean one thing.

AGENTS.md §1 says any number describing our own process is generated by a tool
that scans the artifacts, and a gate fails when the generated value and the
committed one disagree. That rule was followed and the abstract was still wrong,
which is why this file exists: the rule catches a count that *drifted*, and the
defect here was a count that never drifted because it was never the quantity the
sentence claimed.

What went wrong. ``\\NTestReads`` is emitted from
``COUNTERATTACK_WIDE_PROBE.json``'s own ``test_fold_read_index``. That is a
frozen snapshot of where one probe sat in the read sequence when it was written,
and its value is 3. It is a correct number. The abstract then said "a fold this
project read \\NTestReads{} times", and Section~\\ref{sec:external} said
"\\NTestReads{} indexed readings of the official test fold" --- while the ledger
recorded **13 indexed reads across 44 accesses**. One macro was standing for
three different quantities, so no comparison between a generated value and a
committed value could ever fail: each was individually right and the sentence
was wrong.

The two gates here.

1. *Ledger-derived counts track the ledger.* ``\\NIndexedReads``,
   ``\\NFoldAccesses``, ``\\NArchOnFold``, ``\\NUnnamedArch`` and
   ``\\NLineageReads`` must equal what the ledger says today. Planted violation:
   the ledger is edited in a temporary tree and the emitter re-run; the macro
   must follow it, so a macro hard-coded to today's value fails.

2. *A snapshot count may not be used as a programme count.* ``\\NTestReads``
   does not track the ledger, so every place the manuscript uses it must scope
   it in words to the shipped architecture's development. Planted violation: a
   sentence using it with no scoping word, which must be rejected. This is the
   check that would have caught the abstract, and no comparison of numbers
   could have.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
MACROS = ROOT / "paper/frozen_numbers.tex"
MAIN = ROOT / "paper/MAIN_CRYPTOBENCH_GEOAUDIT.tex"
LEDGER = ROOT / "results/official_fold/TEST_FOLD_ACCESS_LEDGER.json"

# macro name -> the ledger field it must equal
LEDGER_BACKED = {
    "NIndexedReads": "n_indexed_reads",
    "NFoldAccesses": "n_standalone_probes",
    "NArchOnFold": "n_distinct_architectures_evaluated",
    "NUnnamedArch": "n_artifacts_with_unnamed_architecture",
}

# A use of \NTestReads is only honest if the sentence says whose reads it counts.
SCOPING = ("table\nfield", "table field", "table\\_field", "lineage",
           "architecture that ships", "development of the table",
           "while it was being built")


def _macro(text: str, name: str) -> str | None:
    m = re.search(r"\\newcommand\{\\%s\}\{([^}]*)\}" % name, text)
    return m.group(1) if m else None


@pytest.fixture(scope="module")
def macros() -> str:
    if not MACROS.is_file():
        pytest.skip("frozen_numbers.tex not built")
    return MACROS.read_text()


@pytest.fixture(scope="module")
def ledger() -> dict:
    if not LEDGER.is_file():
        pytest.skip("ledger not built")
    return json.loads(LEDGER.read_text())


class TestLedgerBackedCounts:
    def test_each_count_equals_the_ledger(self, macros, ledger):
        for name, field in LEDGER_BACKED.items():
            got = _macro(macros, name)
            assert got is not None, f"\\{name} is not emitted"
            assert got == str(ledger[field]), (
                f"\\{name} is {got} and the ledger's {field} is {ledger[field]}")

    def test_lineage_reads_is_derivable_from_the_sequence(self, macros, ledger):
        want = sum(1 for p in ledger["indexed_read_sequence"]
                   if "table field" in (p.get("method") or "").replace("_", " "))
        assert _macro(macros, "NLineageReads") == str(want)

    def test_a_moved_ledger_moves_the_macro(self, tmp_path):
        """Planted: the ledger reports one more indexed read than it does.

        Without this, every assertion above would pass against a macro someone
        typed by hand, which is the shape AGENTS.md §1 was written about.
        """
        if not LEDGER.is_file():
            pytest.skip("ledger not built")
        led = json.loads(LEDGER.read_text())
        led["n_indexed_reads"] += 1
        planted = tmp_path / "TEST_FOLD_ACCESS_LEDGER.json"
        planted.write_text(json.dumps(led))

        sys.path.insert(0, str(ROOT / "tools"))
        import emit_frozen_numbers as efn  # noqa: PLC0415

        real = efn.LEDGER
        try:
            efn.LEDGER = planted
            emitted = efn.build()
        finally:
            efn.LEDGER = real

        assert _macro(emitted, "NIndexedReads") == str(led["n_indexed_reads"]), (
            "the macro did not follow the ledger, so it is not generated from it")

    def test_the_snapshot_count_cannot_exceed_the_indexed_total(self, macros):
        """A lineage's development reads are a subset of the indexed reads."""
        snap = _macro(macros, "NTestReads")
        total = _macro(macros, "NIndexedReads")
        if snap is None or total is None:
            pytest.skip("counts not emitted")
        assert int(snap) <= int(total), (
            f"\\NTestReads is {snap} against {total} indexed reads, which cannot "
            f"be a subset of them")


class TestSnapshotCountIsScoped:
    """The check that would have caught the abstract.

    ``\\NTestReads`` is a frozen probe index, not a programme total, so its every
    appearance has to say so in words. Comparing numbers cannot detect the
    misuse, because the number is right.
    """

    @staticmethod
    def _uses(text: str) -> list[tuple[int, str]]:
        out = []
        for m in re.finditer(r"\\NTestReads\{\}", text):
            lo = max(0, m.start() - 420)
            hi = min(len(text), m.end() + 420)
            line = text[:m.start()].count("\n") + 1
            out.append((line, text[lo:hi]))
        return out

    def test_every_use_in_the_manuscript_is_scoped(self):
        if not MAIN.is_file():
            pytest.skip("manuscript not present")
        bad = [ln for ln, ctx in self._uses(MAIN.read_text())
               if not any(s in ctx for s in SCOPING)]
        assert not bad, (
            "\\NTestReads is a snapshot of one probe's read index, not the "
            f"programme total; these uses do not scope it: lines {bad}. Use "
            "\\NIndexedReads or \\NFoldAccesses for a programme count.")

    def test_an_unscoped_sentence_is_rejected(self):
        """Planted: the sentence the abstract actually carried."""
        planted = (
            "Every number to this point comes from a fold this project read "
            "\\NTestReads{} times while \\NArchOnFold{} of its architectures "
            "were scored on it, so none of them can settle anything.")
        bad = [ln for ln, ctx in self._uses(planted)
               if not any(s in ctx for s in SCOPING)]
        assert bad == [1], (
            "the gate must reject the exact sentence that shipped; if it does "
            "not, it does not express the rule it claims to")

    def test_a_scoped_sentence_is_accepted(self):
        planted = (
            "The architecture that ships was scored on the test fold "
            "\\NTestReads{} times while it was being built.")
        bad = [ln for ln, ctx in self._uses(planted)
               if not any(s in ctx for s in SCOPING)]
        assert not bad


class TestProgrammeCountsAppearAtAll:
    """Separating the macros is worthless if the manuscript stops disclosing.

    The fix could be gamed by scoping every \\NTestReads sentence and never
    mentioning the 13 or the 44 anywhere, which would leave the paper making a
    smaller disclosure than before while passing the gate above.
    """

    def test_the_abstract_states_the_programme_total(self):
        if not MAIN.is_file():
            pytest.skip("manuscript not present")
        text = MAIN.read_text()
        m = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", text, re.S)
        assert m, "no abstract found"
        assert "\\NFoldAccesses{}" in m.group(1), (
            "the abstract must state how many times the held-out fold was "
            "accessed, not only how many times one lineage read it")
        assert "\\NIndexedReads{}" in m.group(1)
