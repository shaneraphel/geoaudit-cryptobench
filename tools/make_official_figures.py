def readme_block(drawn: list[tuple[Path, str]]) -> str:
    """The images and their captions, in the form the README carries them.

    Generated rather than typed, for the reason every other number here is:
    a caption states counts, seeds and a standard error, and a hand-written one
    goes stale the first time the fold is rescored. Captions sit under their
    image because that is where a reader of the manuscript will look for them,
    and nothing is drawn on top of the plot itself.
    """
    out = [BEGIN, ""]
    for i, (path, caption) in enumerate(drawn, 1):
        out.append(f"![Figure {i}](figures/{path.name})")
        out.append("")
        out.append(f"**Figure {i}.** {caption}")
        out.append("")
    out.append(END)
    return "\n".join(out)


def _write_readme(drawn: list[tuple[Path, str]]) -> bool:
    text = README.read_text()
    if BEGIN not in text or END not in text:
        print(f"README is missing the figure markers:\n  {BEGIN}\n  {END}")
        return False
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    README.write_text(head + readme_block(drawn) + tail)
    return True


