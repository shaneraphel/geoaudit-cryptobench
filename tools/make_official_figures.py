def _pocket_camera(xyz, pocket_rows):
    """A camera chosen by the coordinates, not by the author.

    The view direction is the vector from the chain's centroid to the labelled
    pocket's centroid, so the pocket faces the reader. A hand-posed camera would
    say more and could not be regenerated by a Makefile or checked in CI, which is
    the objection ``_projection`` was written to avoid; a rule that points the
    camera at the thing under discussion keeps the 3-D view and answers it.
    """
    import numpy as np
    v = xyz[pocket_rows].mean(axis=0) - xyz.mean(axis=0)
    n = float(np.linalg.norm(v))
    if n < 1e-9:
        return 18.0, -60.0
    v = v / n
    elev = float(np.degrees(np.arcsin(max(-1.0, min(1.0, v[2])))))
    azim = float(np.degrees(np.arctan2(v[1], v[0])))
    return elev, azim


