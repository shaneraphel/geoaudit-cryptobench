def figure_threshold_curve(curve: dict) -> tuple[Path, str]:
    """Every calling fraction, because three of them cannot say they were typical.

    The left panel is the level of each method and the right is the paired
    difference against ours, so the two questions a reader has -- how good is it,
    and is it better than that one -- are not answered by the same line. Both
    baselines and the field are drawn on one axis rather than one panel each: the
    point of the figure is the ordering, and an ordering split across panels has
    to be reassembled by eye.

    Nothing is marked as the best point of any curve, on purpose. The plan behind
    this read forbids choosing from it, and an annotated maximum is how that
    prohibition would quietly stop being true.
    """
    arms = curve["arms"]
    style = {"p2rank": ("#2c7fb8", "P2Rank 2.5.1"),
             "pocketminer": ("#7b3294", "PocketMiner"),
             "plmnn": ("#1a9850", "pLM-NN (CryptoBench's own)")}
    fig, (axl, axr) = plt.subplots(1, 2, figsize=(12.4, 4.4))

    ref = arms["p2rank"]["curve"]
    qs = [r["q"] for r in ref]
    axl.plot(qs, [r["positive_class_f1"]["ours"] for r in ref], "-",
             color="#d94801", lw=2.4, label="Table field (ours)", zorder=4)
    for name, arm in arms.items():
        colour, label = style[name]
        axl.plot([r["q"] for r in arm["curve"]],
                 [r["positive_class_f1"]["theirs"] for r in arm["curve"]],
                 "-", color=colour, lw=1.8, label=label)
    deployed = curve["selects_nothing"]["deployed_q_unchanged"]
    for ax in (axl, axr):
        ax.axvline(deployed, color="#555555", lw=0.9, ls=":", zorder=1)
        ax.grid(alpha=0.22, lw=0.5)
        ax.set_axisbelow(True)
        ax.set_xlabel("fraction of each chain called positive", fontsize=9.5)
    axl.annotate(f"deployed rule, top-{deployed:.0%}\n(chosen on the training "
                 f"fold)", (deployed, axl.get_ylim()[0]), fontsize=7.8,
                 textcoords="offset points", xytext=(6, 16), color="#555555")
    axl.set_ylabel("mean per-structure positive-class F1", fontsize=9.5)
    axl.legend(fontsize=8.2, loc="lower right", frameon=False)

    for name, arm in arms.items():
        colour, label = style[name]
        cq = [r["q"] for r in arm["curve"]]
        mean = [r["positive_class_f1"]["mean"] for r in arm["curve"]]
        lo = [r["positive_class_f1"]["ci"][0] for r in arm["curve"]]
        hi = [r["positive_class_f1"]["ci"][1] for r in arm["curve"]]
        axr.fill_between(cq, lo, hi, color=colour, alpha=0.16, lw=0)
        axr.plot(cq, mean, "-", color=colour, lw=2.0, label=f"minus {label}")
    axr.axhline(0, color="black", lw=1.0)
    axr.set_ylabel("paired difference in F1, ours minus theirs", fontsize=9.5)
    axr.legend(fontsize=8.2, loc="center right", frameon=False)

    fig.tight_layout()
    out = FIGDIR / "fig_threshold_curve.png"
    fig.savefig(out, dpi=200)
    plt.close(fig)

    sp = arms["p2rank"]["sign_span"]["positive_class_f1"]
    excl = sum(1 for r in ref if r["positive_class_f1"]["excludes_zero"])
    behind = [n for n, a in arms.items()
              if a["sign_span"]["positive_class_f1"]["n_where_theirs_is_higher"]
              == a["sign_span"]["positive_class_f1"]["n_cut_points"]]
    tail = ""
    if behind:
        names = " and ".join(style[n][1] for n in behind)
        tail = (f" {names} is ahead of the field at every cut point as well, and "
                f"by margins whose pointwise intervals exclude zero throughout, "
                f"so that deficit is no more a threshold artefact than the "
                f"advantage over P2Rank is.")
    return out, (
        f"The same frozen scores binarised at all {curve['grid']['n']} calling "
        f"fractions from {curve['grid']['low']:.0%} to {curve['grid']['high']:.0%}"
        f", on {arms['p2rank']['n_units']} held-out structures. Left, the level "
        f"each method reaches. Right, the paired difference against the counting "
        f"field with a pointwise 95% bootstrap band. Against P2Rank the field is "
        f"ahead at {sp['n_where_ours_is_higher']} of {sp['n_cut_points']} cut "
        f"points with {sp['sign_changes']} sign changes, so the F1 advantage "
        f"reported at the deployed rule is not an artefact of where the two "
        f"methods were cut; the pointwise interval excludes zero at {excl} of "
        f"them, all at calling fractions well above anything one would deploy, "
        f"so this is a statement about the sign of the difference rather than its "
        f"significance.{tail} No point on any curve was selected: the deployed "
        f"fraction was fixed on the training fold and this read feeds no "
        f"configuration, which is what keeps {curve['grid']['n']} cut points from "
        f"being {curve['grid']['n']} chances to find a favourable one.")


