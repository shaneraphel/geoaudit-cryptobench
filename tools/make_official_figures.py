def _projection(coords: dict[int, "np.ndarray"]):
    """The chain flattened onto its own two longest axes.

    A ribbon rendering would say more, and would need a structure viewer, a
    session file and a hand-chosen camera for each case -- three things that
    cannot be regenerated by a Makefile and cannot be checked by CI. The
    principal-axis projection is chosen by the coordinates rather than by the
    author, and it is enough for the only question these panels ask: did the
    method put its calls where the pocket is.
    """
    import numpy as np
    keys = sorted(coords)
    xyz = np.array([coords[k] for k in keys])
    centred = xyz - xyz.mean(axis=0)
    _, _, vt = np.linalg.svd(centred, full_matrices=False)
    return keys, centred @ vt[:2].T


