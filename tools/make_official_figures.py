def figure_where_we_beat_plmnn(d: dict) -> tuple[Path, str]:
    """Every Set A unit's delta against pLM-NN, with the clear-margin bar marked.

    The confirmatory read already said 27 units favour us and 30 favour them, and
    that the mean is −0.0340. This panel is that split made visible: each bar is
    one unit, green clears a fixed margin (≥0.10 and ours≥0.85), red is the mirror.
    RhoA (9n4c_A) is labelled because its accession is in the frozen set; the mean
    is still a deficit and the caption says so.
    """
    import numpy as np
    rows = d["all_units_sorted_by_ours_minus_plmnn"]
    deltas = np.array([r["ours_minus_plmnn"] for r in rows])
    clear = d["clear_margin_rule"]["ours_minus_plmnn_at_least"]
    colors = ["#1b6b4a" if v >= clear else ("#8a2b2b" if v <= -clear else "#9a9a9a")
              for v in deltas]
    fig, ax = plt.subplots(figsize=(7.4, 4.4))
    ax.barh(range(len(deltas)), deltas[::-1], color=colors[::-1], height=0.85)
    ax.axvline(0, color="black", lw=0.8)
    ax.axvline(clear, color="#1b6b4a", ls="--", lw=0.8, alpha=0.75)
    ax.axvline(-clear, color="#8a2b2b", ls="--", lw=0.8, alpha=0.75)
    ax.set_xlabel("per-unit ROC-AUC: counting field − pLM-NN")
    ax.set_yticks([])
    by = {r["unit"]: i for i, r in enumerate(rows)}
    for r in d.get("named_oncology_gtpases_in_the_clear_margin") or []:
        i = by[r["unit"]]
        ax.annotate(
            f"{r['unit']} RhoA",
            xy=(r["ours_minus_plmnn"], len(rows) - 1 - i),
            xytext=(4, 0), textcoords="offset points", fontsize=8,
            color="#1b6b4a", va="center")
    fig.tight_layout()
    out = FIGDIR / "fig_external_beat_plmnn.png"
    fig.savefig(out, dpi=160)
    plt.close(fig)
    n_c = d["clear_margin_rule"]["n_clear_margin"]
    n_m = d["clear_margin_rule"]["n_clear_margin_mirror"]
    caption = (
        f"Per-unit ROC-AUC difference against pLM-NN on the 57 spent external "
        f"units, sorted. Green bars clear a fixed margin "
        f"(Δ≥{clear:.2f} and ours≥{d['clear_margin_rule']['ours_at_least']}); "
        f"red bars are the mirror. {n_c} clear-margin wins for the counting field, "
        f"{n_m} for pLM-NN. The confirmatory mean remains −0.0340 — this panel "
        f"names the 27/30 split already published, it does not reverse it. "
        f"RhoA (P61586, 9n4c_A) is one clear-margin unit; nothing here is clinical.")
    return out, caption


def main() -> int:
    FIGDIR.mkdir(exist_ok=True)
    boot = json.loads(BOOT.read_text())
    led = json.loads(LEDGER.read_text())
    drawn = [figure_metrics(boot), figure_paired(boot, led)]
    if PREREG_READ.exists():
        drawn.append(figure_functionals(json.loads(PREREG_READ.read_text())))
    if MATCH_READ.exists():
        drawn.append(figure_matched(json.loads(MATCH_READ.read_text())))
    if FULL_READ.exists():
        drawn.append(figure_full_metrics(json.loads(FULL_READ.read_text())))
    if SUBGROUP_READ.exists():
        drawn.append(figure_subgroups(json.loads(SUBGROUP_READ.read_text())))
    if CURVE.exists():
        drawn.append(figure_threshold_curve(json.loads(CURVE.read_text())))
    if CASES.exists():
        drawn.append(figure_cases(json.loads(CASES.read_text())))
        if AUDIT.exists():
            drawn.append(figure_structural_cases(
                json.loads(CASES.read_text()), json.loads(AUDIT.read_text())))
    if DIFFICULTY.exists():
        drawn.append(figure_external_difficulty(
            json.loads(DIFFICULTY.read_text())))
    if SETBC_READ.exists() and SETBC_DIFF.exists():
        # SETBC_DIFF, not DIFFICULTY: the first pass passed Set A's difficulty
        # artifact to the Set B/C figure and raised on a missing key. Two
        # artifacts with near-identical shapes and different subjects is exactly
        # where that happens.
        drawn.append(figure_setbc_read(json.loads(SETBC_READ.read_text()),
                                       json.loads(SETBC_DIFF.read_text())))
    if EMDB.exists():
        got = figure_emdb_resolution()
        if got is not None:
            drawn.append(got)
    if WHERE_WE.exists():
        drawn.append(figure_where_we_beat_plmnn(json.loads(WHERE_WE.read_text())))
    if RHOA.exists():
        drawn.append(figure_rhoa_case(json.loads(RHOA.read_text())))
    if RESIDUE_REC.exists():
        drawn.append(figure_residue_recoveries(json.loads(RESIDUE_REC.read_text())))
    if DUAL_REC.exists():
        drawn.append(figure_dual_baseline_recoveries(json.loads(DUAL_REC.read_text())))
    if SETN_READ.exists():
        drawn.append(figure_setn_read(json.loads(SETN_READ.read_text())))
    if GEOM_PROBE.exists():
        drawn.append(figure_geometry_field_vs_plmnn(
            json.loads(GEOM_PROBE.read_text())))
    if GEOM_LEN.exists():
        drawn.append(figure_geometry_vs_plmnn_by_length(
            json.loads(GEOM_LEN.read_text())))
    images = [p for p, _ in drawn]
    for out in images:
        print(f"wrote {out.relative_to(ROOT)} "
              f"({out.stat().st_size / 1e3:.0f} kB)")
    if not _write_readme(drawn):
        return 1
    print(f"wrote the figure block in {README.relative_to(ROOT)}")

    # Naming the generator is not enough: an image keeps its filename while the
    # numbers underneath it move, and a stale plot passes a name check silently.
    # Recording what each image was drawn from lets the gate fail on the source
    # digest, which is the drift that matters and does not need a plotting
    # library in CI to detect.
    PROVENANCE.write_text(json.dumps({
        "schema": "geoaudit.figure_provenance.v1",
        "clinical_grade": False,
        "purpose": "tie every committed image to the exact bytes it was drawn "
                   "from, so a figure cannot outlive the numbers it shows",
        "generator": "tools/make_official_figures.py",
        "sources": {str(p.relative_to(ROOT)): _sha(p)
                    for p in SOURCES if p.exists()},
        "figures": {p.name: {"sha256": _sha(p), "bytes": p.stat().st_size,
                             "caption": c}
                    for p, c in drawn},
    }, indent=2) + "\n")
    print(f"wrote {PROVENANCE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
