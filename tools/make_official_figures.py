def figure_geometry_vs_plmnn_by_length(d: dict) -> tuple[Path, str]:
    """Length strata of geometry_field vs pLM-NN on the official fold."""
    import numpy as np
    bins = d["length_bins"]
    labels = [b["bin"] for b in bins]
    geo = [b["mean_geometry"] for b in bins]
    plm = [b["mean_plmnn"] for b in bins]
    fig, ax = plt.subplots(figsize=(6.2, 3.8))
    x = np.arange(len(labels))
    w = 0.35
    ax.bar(x - w / 2, geo, w, label="geometry_field", color="#1b6b4a")
    ax.bar(x + w / 2, plm, w, label="pLM-NN", color="#8a2b2b")
    for i, b in enumerate(bins):
        ax.text(i, max(geo[i], plm[i]) + 0.008,
                f"Δ={b['mean_delta']:+.3f}\nn={b['n_units']}",
                ha="center", fontsize=8)
    ax.set_xticks(x)
    ax.set_xticklabels(labels)
    ax.set_ylabel("mean per-unit ROC-AUC")
    ax.set_ylim(0.70, 0.95)
    ax.legend(frameon=False)
    ax.set_title("Official fold: geometry_field vs pLM-NN by chain length")
    fig.tight_layout()
    out = FIGDIR / "fig_geometry_vs_plmnn_by_length.png"
    fig.savefig(out, dpi=160)
    plt.close(fig)
    long = next(b for b in bins if b["bin"] == "n>=300")
    short = next(b for b in bins if b["bin"] == "n<150")
    lo, hi = long["ci95_delta"]
    slo, shi = short["ci95_delta"]
    caption = (
        f"Official CryptoBench test fold stratified by chain length: mean "
        f"per-unit ROC-AUC for geometry_field vs pLM-NN. On n≥300 "
        f"({long['n_units']} units) the point estimate leads "
        f"({long['mean_geometry']:.4f} vs {long['mean_plmnn']:.4f}, "
        f"Δ={long['mean_delta']:+.4f} [{lo:+.4f}, {hi:+.4f}], ahead "
        f"{long['n_geometry_ahead']}/{long['n_plmnn_ahead']}); the CI still "
        f"crosses zero. Short chains (n<150, {short['n_units']} units) sit the "
        f"other way (Δ={short['mean_delta']:+.4f} [{slo:+.4f}, {shi:+.4f}]). "
        f"Fold-mean parity is unchanged. Development stratification; "
        f"clinical_grade is false.")
    return out, caption


