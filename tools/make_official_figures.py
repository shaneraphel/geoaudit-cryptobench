def figure_functionals(read: dict) -> tuple[Path, str]:
    """Why the fold resolves an ordering under one functional and not another.

    Left, the paired differences themselves, because every number on the right
    is a summary of this one histogram and the reader should see the shape
    before the summaries. The win rate is not plotted beside the others: it
    lives on a probability scale and putting it on an axis of ROC-AUC
    differences would invite exactly the cross-scale comparison the selection
    rule refuses to make. It is already in the left panel, as the mass on the
    positive side of zero.
    """
    import numpy as np

    rows = json.loads(TELEMETRY.read_text())["rows"]
    by = {}
    for r in rows:
        if r["method"] in ("table_field", "p2rank") and r.get("residue_auc"):
            by.setdefault(r["method"], {})[r["unit_id"]] = float(r["residue_auc"])
    shared = sorted(set(by["table_field"]) & set(by["p2rank"]))
    d = np.array([by["table_field"][u] - by["p2rank"][u] for u in shared])
    sh = read["shape_of_the_differences"]
    cand = {c["statistic"]: c for c in read["candidates"]}
    k = sh["n_trimmed_each_side"]
    lo_cut, hi_cut = np.sort(d)[k], np.sort(d)[len(d) - k - 1]

    fig, (axh, axf) = plt.subplots(
        1, 2, figsize=(12.4, 3.9), gridspec_kw={"width_ratios": [1.05, 1.35]})

    axh.hist(d, bins=44, color="#7fb1d3", edgecolor="white", linewidth=0.4)
    axh.axvspan(d.min(), lo_cut, color="#bdbdbd", alpha=0.45, lw=0)
    axh.axvspan(hi_cut, d.max(), color="#bdbdbd", alpha=0.45, lw=0)
    axh.axvline(0, color="black", lw=1.0)
    axh.set_xlabel("per-structure ROC-AUC, table field minus P2Rank",
                   fontsize=9.5)
    axh.set_ylabel("structures", fontsize=9.5)
    axh.text(0.02, 0.95,
             f"{sh['n_baseline_ahead']} behind   |   {sh['n_field_ahead']} ahead\n"
             f"shaded: the {k} + {k} the 20% trim discards\n"
             f"discarded losses {sh['worst_losses_mean']:+.3f}, "
             f"wins {sh['best_wins_mean']:+.3f}",
             transform=axh.transAxes, va="top", fontsize=8.3)
    axh.grid(axis="y", alpha=0.22, lw=0.5)
    axh.set_axisbelow(True)

    # The annotations sit in a fixed column rather than trailing each interval,
    # so that five rows of unequal width stay readable and nothing runs off the
    # canvas as the numbers move.
    text_x = 0.068
    ys = list(range(len(FUNCTIONALS)))[::-1]
    for y, (key, label) in zip(ys, FUNCTIONALS):
        c = cand[key]
        resolved = not c["crosses_zero"]
        colour = "#d94801" if resolved else "#8c8c8c"
        axf.plot([c["ci_low"], c["ci_high"]], [y, y], color=colour, lw=2.4,
                 solid_capstyle="butt")
        axf.plot(c["point"], y, "o", color=colour, ms=7, zorder=3)
        axf.text(text_x, y,
                 f"{c['point']:+.4f}  [{c['ci_low']:+.4f}, {c['ci_high']:+.4f}]"
                 f"   p={c['p_two_sided_bootstrap']:.3f}   "
                 f"{'resolved' if resolved else 'contains zero'}",
                 va="center", fontsize=8.6,
                 color="black" if resolved else "#555555")
    axf.axvline(0, color="black", lw=1.0)
    axf.set_yticks(ys)
    axf.set_yticklabels(
        [f"{lab}\n(fixed in advance)" if cand[k]["preregistered"] else lab
         for k, lab in FUNCTIONALS], fontsize=9.5)
    axf.set_xlabel("the same paired differences, summarised five ways",
                   fontsize=9.5)
    axf.set_xlim(-0.03, 0.20)
    axf.grid(axis="x", alpha=0.22, lw=0.5)
    axf.set_axisbelow(True)

    fig.tight_layout()
    out = FIGDIR / "fig_functional_choice.png"
    fig.savefig(out, dpi=200)
    plt.close(fig)

    pre = read["preregistered_result"]
    mean = read["mean_reported_beside_it"]
    wr = next(c for c in read["candidates"] if c["statistic"] == "win_rate")
    caption = (
        f"One set of {sh['n']} paired differences, and what follows from how it "
        f"is summarised. Left, the differences themselves: the field is ahead on "
        f"{sh['n_field_ahead']} structures and behind on {sh['n_baseline_ahead']}, "
        f"a win rate {wr['point']:+.4f} above one half (p={wr['p_two_sided_bootstrap']:.3f}), "
        f"and the shaded tails are what a 20% trim discards \u2014 losses "
        f"averaging {sh['worst_losses_mean']:+.4f} against wins of "
        f"{sh['best_wins_mean']:+.4f}. That asymmetry is why the mean sits at "
        f"{mean['point']:+.4f} while the middle 60% sits at {pre['point']:+.4f}. "
        f"Right, five location summaries of those same numbers with 95% "
        f"bootstrap intervals. The 20% trimmed mean was chosen on the training "
        f"partition and committed in "
        f"{read['provenance_of_the_choice']['committed_in'][:7]} before this "
        f"fold was read for it; the others are shown because reporting only the "
        f"chosen one would hide whether the choice landed on the flattering "
        f"summary. The mean is unresolved and stays in the paper: it is the "
        f"functional that speaks to the discarded tail, where the field's "
        f"failures are worse than P2Rank's.")
    return out, caption


