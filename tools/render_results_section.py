#!/usr/bin/env python3
"""Render the official-fold results block of the README from the frozen JSON.

A results table maintained by hand drifts from the artifacts it summarises, and
the drift is invisible: the prose keeps asserting a method count, a row count and
a point estimate that no longer exist on disk. This repository had exactly that
(a table of six methods describing a run of eight, and a row count of 1152 for a
telemetry file holding 1536 rows).

So the block is generated, not written. Everything between the two markers in
README.md is a pure function of

    results/cryptobench_official/TELEMETRY.json
    results/official_fold/OFFICIAL_MULTI_METHOD_BOOTSTRAP.json
    results/official_fold/OFFICIAL_MULTI_METHOD_BOOTSTRAP_vs_P2RANK.json

and ``--check`` fails if the file disagrees with that function, which is what CI
runs. Interpretation, protocol notes and caveats live OUTSIDE the markers and
stay hand-written; only the numbers are mechanical.

Usage:
    PYTHONPATH=src python3.12 tools/render_results_section.py --check
    PYTHONPATH=src python3.12 tools/render_results_section.py --write
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from pocket_bench.paths import ROOT

BEGIN = "<!-- BEGIN AUTOGENERATED: official fold results -->"
END = "<!-- END AUTOGENERATED: official fold results -->"

README = ROOT / "README.md"
TELEMETRY = ROOT / "results/cryptobench_official/TELEMETRY.json"
MULTI = ROOT / "results/official_fold/OFFICIAL_MULTI_METHOD_BOOTSTRAP.json"
VS_P2RANK = ROOT / "results/official_fold/OFFICIAL_MULTI_METHOD_BOOTSTRAP_vs_P2RANK.json"

METRIC_LABEL = {
    "residue_auc": "ROC-AUC",
    "residue_pr_auc": "PR-AUC",
    "residue_mcc": "MCC",
    "residue_f1": "F1",
}
METRIC_ORDER = ("residue_auc", "residue_pr_auc", "residue_mcc", "residue_f1")


def _fmt(x: float | None, digits: int = 3) -> str:
    return "null" if x is None else f"{x:.{digits}f}"


def _cell(entry: dict | None) -> str:
    if entry is None or entry.get("point") is None:
        return "null"
    return (f"{_fmt(entry['point'])} "
            f"[{_fmt(entry.get('ci_low'))}, {_fmt(entry.get('ci_high'))}]")


def _signed(x: float | None) -> str:
    return "null" if x is None else f"{x:+.3f}"


def render() -> str:
    tel = json.loads(TELEMETRY.read_text())
    rows = tel["rows"]
    multi = json.loads(MULTI.read_text())["metrics"]
    vs = json.loads(VS_P2RANK.read_text())["metrics"]

    methods = sorted({r["method"] for r in rows})
    units = sorted({r["unit_id"] for r in rows})
    n_avail = sum(1 for r in rows if r.get("residue_metrics_available"))
    n_ok = sum(1 for r in rows if r.get("status") == "OK")
    runtime = sum(r.get("runtime_s") or 0.0 for r in rows)
    multi_chain = sorted({p for p in {r["pdb"] for r in rows}
                          if sum(1 for u in units if u.startswith(p + "_")) > 1})

    out: list[str] = [BEGIN, ""]
    out.append(
        f"**Execution guarantee.** The official evaluation emits "
        f"**{len(rows)}/{len(rows)}** telemetry rows = **{len(units)} evaluation "
        f"units x {len(methods)} methods**, with `residue_metrics_available=true` "
        f"on {n_avail}/{len(rows)}, `status=OK` on {n_ok}/{len(rows)}, and zero "
        f"silent drops. The evaluation unit is a `(pdb, chain)` pair (`unit_id`), "
        f"not a PDB entry: "
        + (f"{len(units)} units span {len({r['pdb'] for r in rows})} distinct "
           f"entries because "
           + " and ".join(f"`{p}`" for p in multi_chain)
           + f" contribute two chains each. "
           if multi_chain else "")
        + f"All four metrics resample over n={len(units)}; `per_structure_values` "
          f"raises on a colliding `unit_id` rather than overwriting a row. "
          f"Summed cost recorded in telemetry: {runtime:.0f} s over the "
          f"{len(rows)} `runtime_s` fields."
    )
    out.append("")
    out.append("Point estimates [95 % CI] over units, `n_boot=10000`, seed "
               "`20260725`:")
    out.append("")
    out.append("| method | " + " | ".join(METRIC_LABEL[m] for m in METRIC_ORDER)
               + " |")
    out.append("|---|" + "---|" * len(METRIC_ORDER))

    def sort_key(m: str) -> float:
        pt = multi["residue_auc"]["per_method"].get(m, {}).get("point")
        return -(pt if pt is not None else -9.0)

    for m in sorted(methods, key=sort_key):
        cells = [_cell(multi[k]["per_method"].get(m)) for k in METRIC_ORDER]
        out.append(f"| `{m}` | " + " | ".join(cells) + " |")
    out.append("")

    out.append("Paired difference against `p2rank` (same resample indices, "
               "so the comparison is within-unit):")
    out.append("")
    out.append("| method | " + " | ".join(
        f"{METRIC_LABEL[m]} delta [95 % CI]" for m in METRIC_ORDER) + " |")
    out.append("|---|" + "---|" * len(METRIC_ORDER))
    for m in sorted(methods, key=sort_key):
        if m == "p2rank":
            continue
        cells = []
        for k in METRIC_ORDER:
            d = vs[k]["paired_vs_baseline"].get(m)
            if d is None or d.get("delta_point") is None:
                cells.append("null")
                continue
            mark = "ns" if d.get("crosses_zero") else "**sig**"
            cells.append(f"{_signed(d['delta_point'])} "
                         f"[{_signed(d.get('delta_ci_low'))}, "
                         f"{_signed(d.get('delta_ci_high'))}] {mark}")
        out.append(f"| `{m}` | " + " | ".join(cells) + " |")
    out.append("")
    out.append("`ns` = the 95 % CI of the paired difference contains zero, i.e. "
               "the fold does not separate that method from P2Rank on that "
               "metric. `**sig**` = it does, in P2Rank's favour wherever the "
               "difference is negative.")
    out.append("")
    out.append(END)
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true",
                   help="exit 1 if README disagrees with the frozen JSON")
    g.add_argument("--write", action="store_true",
                   help="rewrite the block in place")
    args = ap.parse_args(argv)

    text = README.read_text()
    if BEGIN not in text or END not in text:
        print(f"README is missing the markers:\n  {BEGIN}\n  {END}",
              file=sys.stderr)
        return 2
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    block = render()

    if args.write:
        README.write_text(head + block + tail)
        print(f"rewrote the official-fold block in {README.name}")
        return 0

    current = BEGIN + rest.split(END, 1)[0] + END
    if current.strip() == block.strip():
        print("README results block matches the frozen JSON")
        return 0
    print("README results block DISAGREES with the frozen JSON.\n"
          "Run: PYTHONPATH=src python3.12 tools/render_results_section.py --write",
          file=sys.stderr)
    cur_lines = current.strip().splitlines()
    new_lines = block.strip().splitlines()
    for i in range(max(len(cur_lines), len(new_lines))):
        a = cur_lines[i] if i < len(cur_lines) else "<absent>"
        b = new_lines[i] if i < len(new_lines) else "<absent>"
        if a != b:
            print(f"  line {i + 1}\n    README: {a}\n    frozen: {b}",
                  file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
