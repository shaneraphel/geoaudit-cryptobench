"""Draw the training-fold architecture findings, and nothing from the test fold.

Why this is a separate generator
--------------------------------
``make_official_figures.py`` says in its first line that it draws the
official-fold comparison and nothing else, and that sentence is there because a
figure drawn from the wrong population sat in this repository for weeks being
read faster than the text that would have corrected it. These figures are drawn
from cluster-disjoint halves of the **training** fold. Putting them in that
generator would make one file that draws from two populations, and the next
person to add a panel would have to work out which they were in.

What is drawn, and why these two
--------------------------------
Figure A1, per-unit ROC-AUC against the number of cryptic residues in the unit.
Eight readout parameters and five wire families were swept in this repository
and every one of them was scored by a mean over units. That summary hides what
this panel shows at a glance: the deployed field scores 0.5991 on the 188 units
with fewer than ten cryptic residues and 0.8766 on the 201 with more than
twenty-two, and 87 units score below one half. The strip of points below the
0.5 line is the population that a threshold metric is destroyed by, which is
where the withdrawn F1 and MCC claims went.

Figure A2, the spatial gate swept per stratum, with the deployed radius marked.
It carries two things the text needs. The deployed ``r=18`` is not the best
radius for any stratum, and it is the worst of thirteen arms for the smallest.
And the improvement from ``r=14`` is the same size in every stratum, which is
what rules out the reading this sweep was launched to test -- that the optimum
radius rises with pocket size -- and makes it a better global constant instead.

No image carries a title. The descriptive text is emitted from the same
artifacts the plots are drawn from, into ARCHITECTURE_FIGURE_PROVENANCE.json and
into the README block, so a caption stating a unit count is generated like any
other perishable number here.

Usage: PYTHONPATH=src python3.12 tools/make_architecture_figures.py
"""
