def fig_failure_tail(tail: dict) -> tuple[Path, str]:
    st = tail["stratified_by_positive_count"]
    labels = [f"{s['n_cryptic_from']}\u2013{s['n_cryptic_below'] - 1}"
              for s in st]
    means = [s["mean_auc"] for s in st]
    meds = [s["median_auc"] for s in st]
    sds = [s["sd_of_auc"] for s in st]
    nulls = [s["null_sampling_se_at_this_size"] for s in st]
    below = [s["share_below_one_half"] for s in st]
    ns = [s["n_units"] for s in st]

    fig, ax = plt.subplots(1, 2, figsize=(11.0, 4.2))
    x = np.arange(len(st))

    ax[0].errorbar(x, means, yerr=sds, fmt="o", color=ORANGE, capsize=4,
                   markersize=7, linewidth=1.6, label="mean \u00b1 1 sd")
    ax[0].plot(x, meds, "s", color=BLUE, markersize=6, label="median")
    ax[0].errorbar(x, means, yerr=nulls, fmt="none", ecolor=GREY,
                   capsize=8, linewidth=2.4,
                   label="null sampling se at this size")
    ax[0].axhline(0.5, color="k", linewidth=0.8, linestyle=":")
    ax[0].set_xticks(x)
    ax[0].set_xticklabels([f"{a}\nn={b}" for a, b in zip(labels, ns)])
    ax[0].set_xlabel("cryptic residues in the unit")
    ax[0].set_ylabel("per-unit ROC-AUC")
    ax[0].set_ylim(0.35, 1.0)
    ax[0].legend(loc="lower right", fontsize=8, frameon=False)

    ax[1].bar(x, [100 * b for b in below], color=ORANGE, width=0.6)
    for xi, b in zip(x, below):
        ax[1].text(xi, 100 * b + 0.8, f"{100 * b:.1f}%", ha="center",
                   fontsize=9)
    ax[1].set_xticks(x)
    ax[1].set_xticklabels(labels)
    ax[1].set_xlabel("cryptic residues in the unit")
    ax[1].set_ylabel("units scoring below 0.5  (%)")
    ax[1].set_ylim(0, max(100 * b for b in below) * 1.25)
    for a in ax:
        a.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    out = FIGDIR / "fig_failure_tail.png"
    fig.savefig(out, dpi=180)
    plt.close(fig)

    p = tail["per_unit_auc"]
    t = tail["tail"]
    cap = (
        f"Where the detector fails, on {p['n']} training units scored on the "
        f"pick half of twelve cluster-disjoint splits. Left, per-unit ROC-AUC "
        f"by the number of cryptic residues the unit contains: mean with one "
        f"standard deviation in orange, median in blue, and in grey the "
        f"sampling standard error a within-unit AUC has at that size under the "
        f"null. The spread is inflated beyond that null at every size and most "
        f"at the smallest, so part of the width is the metric rather than the "
        f"detector; the mean is not, because sampling noise is symmetric and "
        f"the mean falls from "
        f"{st[-1]['mean_auc']:.4f} to {st[0]['mean_auc']:.4f} across the "
        f"strata. Right, the share of units in each stratum scoring below one "
        f"half, which is worse than a coin toss on their own residues: "
        f"{t['n_units_below_one_half']} units do, and they are the population a "
        f"threshold metric is destroyed by. Every architecture sweep in this "
        f"repository was scored by a mean over units, which is "
        f"{p['mean']:.4f} here against a median of {p['median']:.4f}.")
    return out, cap


def fig_gate_by_stratum(gate: dict) -> tuple[Path, str]:
    arms = gate["arms"]
    dep_r = gate["arms"]["r=18 w=1"]["radius"]
    strat = [f"{b['n_cryptic_from']}\u2013{b['n_cryptic_below'] - 1}"
             for b in arms["r=18 w=1"]["by_stratum"]]

    fig, ax = plt.subplots(1, 2, figsize=(11.0, 4.2))
    for i, sn in enumerate(strat):
        rs, vs = [], []
        for k, v in arms.items():
            if v["weight"] != 1.0 or v["radius"] == 0.0:
                continue
            rs.append(v["radius"])
            vs.append(v["by_stratum"][i]["mean_auc"])
        o = np.argsort(rs)
        ax[0].plot(np.asarray(rs)[o], np.asarray(vs)[o], "o-", markersize=5,
                   linewidth=1.5, label=f"{sn} cryptic")
    ax[0].axvline(dep_r, color=GREY, linestyle="--", linewidth=1.2)
    ax[0].text(dep_r + 0.4, ax[0].get_ylim()[0] + 0.01, "deployed",
               color=GREY, fontsize=8, rotation=90, va="bottom")
    ax[0].set_xlabel("gate radius (\u00c5), weight 1.0")
    ax[0].set_ylabel("per-unit ROC-AUC")
    ax[0].legend(fontsize=8, frameon=False)

    pv = gate["paired_against_the_deployed_gate"]["r=14 w=1"]
    keys = ["pooled"] + [s.replace("\u2013", "-") for s in strat]
    ys = np.arange(len(keys))[::-1]
    for yi, k in zip(ys, keys):
        v = pv[k]
        ax[1].plot([v["ci95"][0], v["ci95"][1]], [yi, yi], color=BLUE,
                   linewidth=2.0)
        ax[1].plot([v["mean"]], [yi], "o", color=BLUE, markersize=6)
        ax[1].text(0.0055, yi, f"{v['n_units_better']}/{v['n_units']}",
                   fontsize=8, va="center", color=GREY)
    ax[1].axvline(0.0, color="k", linewidth=0.9)
    ax[1].set_yticks(ys)
    ax[1].set_yticklabels(keys)
    ax[1].set_xlabel("paired ROC-AUC, r=14 minus the deployed r=18")
    ax[1].set_xlim(-0.006, 0.009)
    for a in ax:
        a.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    out = FIGDIR / "fig_gate_by_stratum.png"
    fig.savefig(out, dpi=180)
    plt.close(fig)

    sc = gate["selection_check"]
    pooled = pv["pooled"]
    cap = (
        f"The spatial gate swept per pocket size on the training fold, thirteen "
        f"arms sharing one compile per split. Left, per-unit ROC-AUC against "
        f"gate radius at weight 1.0, one line per stratum; the deployed radius "
        f"is marked and is the best for no stratum. Right, the paired "
        f"difference between r=14 and the deployed r=18 on the same units, with "
        f"95% intervals and the count of units improved: "
        f"{pooled['mean']:+.5f} pooled, interval "
        f"[{pooled['ci95'][0]:+.5f}, {pooled['ci95'][1]:+.5f}], "
        f"{pooled['n_units_better']} of {pooled['n_units']} units better, and "
        f"the same size in every stratum rather than concentrated in the small "
        f"pockets the sweep was launched to investigate. Choosing the arm on "
        f"six splits and scoring it on the other six selects the same arm both "
        f"ways round and gives margins of "
        f"{sc['chose_on_splits_0_scored_on_1']['margin_where_it_was_not']:+.5f} "
        f"and "
        f"{sc['chose_on_splits_1_scored_on_0']['margin_where_it_was_not']:+.5f}, "
        f"so the choice replicates and the size is uncertain within that range. "
        f"Nothing is changed on the strength of this: the constant is still "
        f"r=18 and moving it would spend the external confirmation.")
    return out, cap


def render_readme(drawn: list[tuple[Path, str]]) -> None:
    body = [BEGIN, ""]
    for i, (p, cap) in enumerate(drawn, start=1):
        body.append(f"![Architecture figure {i}](figures/{p.name})")
        body.append("")
        body.append(f"**Architecture figure {i}.** {cap}")
        body.append("")
    body.append(END)
    text = README.read_text()
    block = "\n".join(body)
    if BEGIN in text and END in text:
        a = text.index(BEGIN)
        b = text.index(END) + len(END)
        text = text[:a] + block + text[b:]
    else:
        marker = "## Repository layout"
        if marker not in text:
            raise SystemExit("cannot place the architecture figure block: "
                             "neither the markers nor the layout heading found")
        text = text.replace(marker, block + "\n\n" + marker, 1)
    README.write_text(text)


def fig_four_recoveries(doc: dict) -> tuple[Path, str]:
    """The four clean cases, the empty mirror, and the P2Rank-only case study.

    Architecture figure 3 already shows every unit as a point. This panel exists
    so a reader who lands on the recovery section sees the count before the
    scatter: four named chains under the strict rule, not a long list, with the
    mirror empty beside them and ``4m7p_A`` drawn only against P2Rank.
    """
    found = float(doc["rule"]["found_at_or_above"])
    missed = float(doc["rule"]["missed_at_or_below"])
    # README table order, strongest margin first; reverse so that unit sits at
    # the top of a horizontal bar chart (matplotlib draws y=0 at the bottom).
    by_unit = {r["unit"]: r for r in doc["recovered"]}
    table_order = ("2xur_B", "8bdi_I", "5f3k_B", "8c3u_A")
    rows = [by_unit[u] for u in table_order if u in by_unit]
    for r in doc["recovered"]:
        if r["unit"] not in {x["unit"] for x in rows}:
            rows.append(r)
    rows = list(reversed(rows))
    caveat = list(doc.get("recovered_but_the_file_is_parsed_differently") or [])
    n_units = int(doc["n_units_compared"])
    n_rec = int(doc["n_recovered"])
    n_mir = int(doc["n_mirror"])

    fig = plt.figure(figsize=(11.8, 5.6))
    gs = fig.add_gridspec(
        1, 2, width_ratios=[1.55, 1.0], wspace=0.32,
        left=0.14, right=0.98, top=0.90, bottom=0.12)
    ax = fig.add_subplot(gs[0, 0])
    axr = fig.add_subplot(gs[0, 1])

    y = np.arange(len(rows))
    h = 0.22
    ours_c, p2_c, pm_c = GREEN, BLUE, ORANGE
    for i, r in enumerate(rows):
        ax.barh(i + h, r["ours"], height=h * 0.9, color=ours_c, zorder=3)
        ax.barh(i, r["p2rank"], height=h * 0.9, color=p2_c, zorder=3)
        ax.barh(i - h, r["pocketminer"], height=h * 0.9, color=pm_c, zorder=3)
        for dy, val, col in (
            (h, r["ours"], ours_c),
            (0.0, r["p2rank"], p2_c),
            (-h, r["pocketminer"], pm_c),
        ):
            ax.text(val + 0.012, i + dy, f"{val:.3f}", va="center",
                    fontsize=8.0, color=col)
        ax.text(-0.02, i, f"{r['unit']}\n{r['n_residues']} res, "
                          f"{r['n_cryptic']} cryptic",
                transform=ax.get_yaxis_transform(), ha="right", va="center",
                fontsize=8.6)

    ax.axvline(found, color=ours_c, lw=1.1, ls="--", zorder=2)
    ax.axvline(missed, color=RED, lw=1.1, ls="--", zorder=2)
    ax.axvline(0.5, color="#bbbbbb", lw=0.8, zorder=1)
    ax.text(found, len(rows) - 0.35 + 0.55, f"ours ≥ {found:.2f}",
            color=ours_c, fontsize=8.2, ha="center", va="bottom")
    ax.text(missed, len(rows) - 0.35 + 0.55, f"baselines ≤ {missed:.2f}",
            color=RED, fontsize=8.2, ha="center", va="bottom")
    ax.set_yticks([])
    ax.set_xlim(0.0, 1.05)
    ax.set_ylim(-0.7, len(rows) - 0.3 + 0.55)
    ax.set_xlabel("within-unit ROC-AUC", fontsize=9.5)
    ax.text(0.0, 1.02,
            f"{n_rec} clean cases of {n_units} training units — not hundreds",
            transform=ax.transAxes, fontsize=10.0, ha="left", va="bottom")
    ax.grid(axis="x", alpha=0.25, lw=0.5)
    ax.set_axisbelow(True)
    ax.legend(
        handles=[
            plt.Rectangle((0, 0), 1, 1, color=ours_c, label="counting field"),
            plt.Rectangle((0, 0), 1, 1, color=p2_c, label="P2Rank"),
            plt.Rectangle((0, 0), 1, 1, color=pm_c, label="PocketMiner"),
        ],
        loc="lower right", fontsize=8.2, frameon=False, ncol=1)

    # Right: mirror empty + 4m7p vs P2Rank only.
    axr.set_xlim(0, 1)
    axr.set_ylim(0, 1)
    axr.axis("off")
    axr.text(0.0, 0.96, "Mirror under the same rule",
             fontsize=10.0, fontweight="bold", va="top")
    axr.text(0.0, 0.88,
             f"both baselines ≥ {found:.2f} and counting field ≤ {missed:.2f}",
             fontsize=8.4, color="#444444", va="top")
    axr.add_patch(plt.Rectangle((0.0, 0.58), 1.0, 0.22, facecolor="#f2c9c9",
                                edgecolor=RED, lw=1.2, transform=axr.transAxes,
                                clip_on=False))
    axr.text(0.5, 0.69, f"{n_mir} units",
             transform=axr.transAxes, ha="center", va="center",
             fontsize=22, fontweight="bold", color=RED)
    axr.text(0.5, 0.61, "the reverse disagreement is empty",
             transform=axr.transAxes, ha="center", va="center",
             fontsize=8.6, color=RED)

    axr.text(0.0, 0.48, "Case study vs P2Rank only — not one of the four",
             fontsize=10.0, fontweight="bold", va="top")
    if caveat:
        r = caveat[0]
        axr.text(0.0, 0.40,
                 f"{r['unit']}  ·  {r['n_residues']} residues, "
                 f"{r['n_cryptic']} cryptic  ·  ensemble deposit",
                 fontsize=8.4, color="#444444", va="top")
        # Two bars against a common axis drawn in data coords via inset.
        inset = axr.inset_axes([0.0, 0.08, 1.0, 0.26])
        labels = ["counting field", "P2Rank"]
        vals = [r["ours"], r["p2rank"]]
        cols = [ours_c, p2_c]
        inset.barh([1, 0], vals, color=cols, height=0.55, zorder=3)
        for yi, val, col in zip([1, 0], vals, cols):
            inset.text(val + 0.015, yi, f"{val:.3f}", va="center",
                       fontsize=9.0, color=col)
        inset.axvline(found, color=ours_c, lw=1.0, ls="--")
        inset.axvline(missed, color=RED, lw=1.0, ls="--")
        inset.axvline(0.5, color="#bbbbbb", lw=0.8)
        inset.set_yticks([1, 0])
        inset.set_yticklabels(labels, fontsize=8.4)
        inset.set_xlim(0, 1.05)
        inset.set_xlabel("within-unit ROC-AUC", fontsize=8.4)
        inset.grid(axis="x", alpha=0.25, lw=0.5)
        inset.set_axisbelow(True)
        axr.text(0.0, 0.02,
                 "same 390-residue universe as P2Rank; excluded from the joint "
                 "table because not every baseline parses the ensemble alike",
                 fontsize=7.8, color="#555555", va="bottom", wrap=True)

    out = FIGDIR / "fig_four_recoveries.png"
    fig.savefig(out, dpi=200)
    plt.close(fig)

    caveat_bit = ""
    if caveat:
        r = caveat[0]
        caveat_bit = (
            f" Right: the mirror under the same rule is empty ({n_mir} units), "
            f"and {r['unit']} is shown only against P2Rank — "
            f"{r['ours']:.3f} vs {r['p2rank']:.3f} on the same "
            f"{r['n_residues']} residues — as a training-fold case study, not "
            f"one of the four."
        )
    cap = (
        f"Four clean recoveries on the training fold, not hundreds. Left: the "
        f"{n_rec} units where the counting field scores within-unit ROC-AUC "
        f"≥ {found:.2f} while both P2Rank and PocketMiner sit ≤ {missed:.2f} "
        f"(chance 0.50), out of {n_units} units where all three methods are "
        f"defined. Each unit shows all three scores; the dashed lines are the "
        f"two cuts fixed before the counts were read."
        f"{caveat_bit} Exploratory, training fold only; pLM-NN is absent; "
        f"clinical_grade is false."
    )
